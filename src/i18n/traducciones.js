const normalizar = (valor) =>
  String(valor || "")
    .replace(/\s+/g, " ")
    .trim();

const preservarEspacios = (original, traducido) => {
  const inicio = original.match(/^\s*/)?.[0] || "";
  const fin = original.match(/\s*$/)?.[0] || "";
  return `${inicio}${traducido}${fin}`;
};

export function traducirTexto(texto, idioma = "es") {
  if (idioma === "es") return texto;
  const original = String(texto ?? "");
  const limpio = normalizar(original);
  if (!limpio) return texto;

  const diccionario = textos[idioma] || {};
  const directo = diccionario[limpio];
  if (directo) return preservarEspacios(original, directo);

  const conDosPuntos = limpio.match(/^(.+):$/);
  if (conDosPuntos && diccionario[conDosPuntos[1]]) {
    return preservarEspacios(original, `${diccionario[conDosPuntos[1]]}:`);
  }

  const notificaciones = limpio.match(/^(\d+)\s+notificaciones sin leer$/i);
  if (notificaciones) {
    return preservarEspacios(original, `${notificaciones[1]} ${diccionario["notificaciones sin leer"] || "unread notifications"}`);
  }

  const mensajes = limpio.match(/^(\d+)\s+mensajes sin leer$/i);
  if (mensajes) {
    return preservarEspacios(original, `${mensajes[1]} ${diccionario["mensajes sin leer"] || "unread messages"}`);
  }

  const saludo = limpio.match(/^(Buenos dias|Buenos días|Buenas tardes|Buenas noches),\s*(.+)$/);
  if (saludo && diccionario[saludo[1]]) {
    return preservarEspacios(original, `${diccionario[saludo[1]]}, ${saludo[2]}`);
  }

  return texto;
}

export function obtenerTraductor(idioma = "es") {
  return (texto) => traducirTexto(texto, idioma);
}
